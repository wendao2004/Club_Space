/**
 * 绝杀识别的测试。
 *
 * 这个文件的做法是**先立前提、再验结论**：
 *   1. 摆出一个局面，把你认定的"成杀那一手"当成一个普通着法去走；
 *   2. 断言引擎判定它是**将死**（前提不成立就说明我摆错了，测试立刻红）；
 *   3. 才断言识别出来的杀法名。
 *
 * 为什么非要这样：杀法名是给人看的，摆错一个子就会变成"其实是将不死"，
 * 而那种局面下识别器给出什么名字都毫无意义。**先把"这确实是将死"钉住**，
 * 名字的断言才有分量。
 *
 * 用法：node scripts/xiangqi-mate-test.mjs   （纯逻辑，不需要服务端）
 */

import {
  applyMove,
  deserializeBoard,
  evaluateResult,
  legalMoves,
  squareName,
} from '../server/src/games/xiangqi.ts'
import { classifyMate } from '../server/src/games/xiangqi-mates.ts'

let passed = 0
let failed = 0

function ok(name, extra = '') {
  passed++
  console.log(`  \x1b[32m✓\x1b[0m ${name}${extra ? `  \x1b[90m${extra}\x1b[0m` : ''}`)
}

function bad(name, detail) {
  failed++
  console.log(`  \x1b[31m✗\x1b[0m ${name}\n      \x1b[31m${detail}\x1b[0m`)
}

function assert(cond, name, detail = '') {
  if (cond) ok(name, detail)
  else bad(name, detail || '断言失败')
}

/** 内部格号：row 0 = 黑方底线。 */
const sq = (row, col) => row * 9 + col

/**
 * 摆局面 → 走那一手 → 先确认是将死 → 再确认识别出的杀法名。
 *
 * @param label     这一步的说明（打印用）
 * @param boardText 成杀**之前**的局面
 * @param from,to   成杀的那一手（内部格号）
 * @param expected  期望识别出的杀法名
 */
function checkPattern(label, boardText, from, to, expected) {
  const before = deserializeBoard(boardText)
  const legal = legalMoves(before, 'red')
  const move = legal.find((m) => m.from === from && m.to === to)
  if (!move) {
    bad(`${label}：测试前提（这一步得是合法着法）`, `${squareName(from)}->${squareName(to)} 不在红方合法着法里`)
    return
  }

  const after = applyMove({ board: before, turn: 'red', history: [] }, move)
  const verdict = evaluateResult(after)
  if (!verdict.over || verdict.reason !== 'checkmate') {
    bad(
      `${label}：测试前提（这一步得是将死）`,
      `引擎判为 ${verdict.over ? verdict.reason : '未结束'}，黑方还有 ${legalMoves(after.board, 'black').length} 步可走｜局面 ${boardText}`,
    )
    return
  }

  const pattern = classifyMate(after.board, move, 'black')
  assert(
    pattern?.name === expected,
    `${label}：识别为「${expected}」`,
    pattern ? `实际识别为「${pattern.name}」· ${pattern.detail}` : '没有识别出任何杀法',
  )
}

console.log('\n\x1b[1m【绝杀识别】\x1b[0m')

// ---------------------------------------------------------------- 对面笑
// 黑将 d9；红车 h0 沉底照将（横线）；黑将的三个逃格里，
// c9 被红车 c0 封住、d8 被红马封住，而 e9 在红帅那条竖线上 —— 走过去就照面。
// 黑将 d9 的逃格有三个：c9（红马封）、d8（红马封）、e9 ——
// e9 正好在红帅那条竖线上且中间无子，而且**没有任何红子能打到它**：
// 黑将一步都不敢往那儿走，这就是靠照面规则封死的退路。
// （成杀那一手是红车平到 d 线照将 —— 它走的是竖线，所以够不着 e9。）
checkPattern(
  '对面笑',
  [
    '...k.....', // 黑将 d9
    '.........',
    '.N.......', // 红马 b7（封 c9 与 d8）
    '.........',
    '.........',
    'R........', // 红车 a4 —— 待走 d4
    '.........',
    '.........',
    '.........',
    '....K....', // 红帅 e0（照面规则的来源）
  ].join('/'),
  sq(5, 0),
  sq(5, 3),
  '对面笑',
)

// ---------------------------------------------------------------- 卧槽马
// 红马跳到 c7（对方 3 路 7 线 = "槽"位）将军；d9、e9、d8 三格分别被红车、红兵封死。
checkPattern(
  '卧槽马',
  [
    '...k.....', // 黑将 d9
    '....P....', // 红兵 e8（封 e9）
    '...P.....', // 红兵 d7（封 d8）
    'N........', // 红马 a6 —— 待跳 c7
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '..R.K....', // 红车 c0（封 c9）、红帅 e0
  ].join('/'),
  sq(3, 0),
  sq(2, 2),
  '卧槽马',
)

// ---------------------------------------------------------------- 钓鱼马
// 红马跳到 c8（对方 3 路 8 线）将军：钩住九宫上角，两车封住 d9/f9，红兵封 e8。
checkPattern(
  '钓鱼马',
  [
    '....k....', // 黑将 e9
    '.........',
    'N...P....', // 红马 a7（待跳 c8）、红兵 e7
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '...RKR...', // 红车 d0、红帅 e0、红车 f0
  ].join('/'),
  sq(2, 0),
  sq(1, 2),
  '钓鱼马',
)

// ---------------------------------------------------------------- 挂角马
// 红马跳到 d7（九宫两角的斜下方）将军：同样靠两车 + 红兵封死逃格。
// 注意：马落 d7 正好挡住 d 线，所以 d9 不能靠"车在 d 线上"来封 ——
// 改由红马 c7 兼管 d9 与 e8，f9 由红车 f0 封。
checkPattern(
  '挂角马',
  [
    '..N.k....', // 红马 c9（待跳 d7）、黑将 e9
    '.........',
    '..N.P....', // 红马 c7（封 d9）、红兵 e7（封 e8）
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '....KR...', // 红帅 e0、红车 f0（封 f9）
  ].join('/'),
  sq(0, 2),
  sq(2, 3),
  '挂角马',
)

// ---------------------------------------------------------------- 双车错
// 红车从 a1 平到 e1 照将（e 线），另一只车在 a8 封着 e8；
// 两只马把 d9、f9 也封死 —— 两车一错，将没有退路。
checkPattern(
  '双车错',
  [
    '....k....', // 黑将 e9
    'R........', // 红车 a8（封 e8）
    '..N...N..', // 红马 c7、g7（封 d9 / f9）
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    'R........', // 红车 a1 —— 待走 e1
    '...K.....', // 红帅 d0
  ].join('/'),
  sq(8, 0),
  sq(8, 4),
  '双车错',
)

// ---------------------------------------------------------------- 立马车
// 红车开到 e8 贴脸照将，黑将吃不动它 —— 有红马 c7 护着这辆车。
checkPattern(
  '立马车',
  [
    '....kp...', // 黑将 e9、黑卒 f9（堵住 f9）
    'R........', // 红车 a8 —— 待走 e8
    '..N......', // 红马 c7（护车，同时封 d9）
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '...K.....', // 红帅 d0
  ].join('/'),
  sq(1, 0),
  sq(1, 4),
  '立马车',
)

// ---------------------------------------------------------------- 马后炮
// 红炮平到 e0，隔着 e8 的红马照将（马当炮架）；黑将吃马没用 ——
// 吃了之后士/马都成了新的炮架，照样将。
checkPattern(
  '马后炮',
  [
    '...aka...', // 黑士 d9、黑将 e9、黑士 f9
    'R...N....', // 红车 a8（护马）、红马 e8（炮架）
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    'C....K...', // 红炮 a0 —— 待走 e0、红帅 f0
  ].join('/'),
  sq(9, 0),
  sq(9, 4),
  '马后炮',
)

// ---------------------------------------------------------------- 重炮
// 红炮平到 e0，隔着 e1 的另一只红炮照将。将往 e8 退也躲不掉：
// 炮的射线正好穿过前炮打到它。
checkPattern(
  '重炮',
  [
    '...aka...', // 黑士 d9、黑将 e9、黑士 f9
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '....C....', // 红炮 e1（炮架）
    'C....K...', // 红炮 a0 —— 待走 e0、红帅 f0
  ].join('/'),
  sq(9, 0),
  sq(9, 4),
  '重炮',
)

// ---------------------------------------------------------------- 沉底车
// 红车沉到底线照将，两只马与一只兵封死全部逃格。
checkPattern(
  '沉底车',
  [
    '....k....', // 黑将 e9
    '.........',
    '..N.P.N..', // 红马 c7、红兵 e7、红马 g7
    '.........',
    '.........',
    'R........', // 红车 a4 —— 待走 a9
    '.........',
    '.........',
    '.........',
    '...K.....', // 红帅 d0
  ].join('/'),
  sq(5, 0),
  sq(0, 0),
  '沉底车',
)

// ---------------------------------------------------------------- 小兵杀（兜底）
// 只有一个小兵顶上去照将，但逃格全被自己的子堵住、退格被红车护着 —— 也是将死。
checkPattern(
  '小兵杀（兜底分支）',
  [
    '...rkp...', // 黑车 d9、黑将 e9、黑卒 f9
    'R........', // 红车 a8（护住 e8）
    '....P....', // 红兵 e7 —— 待走 e8
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '.........',
    '....K....', // 红帅 e0（不能在 d 线上：黑车 d9 正照着那条线）
  ].join('/'),
  sq(2, 4),
  sq(1, 4),
  '小兵杀',
)

// ---------------------------------------------------------------- 识别不出来就老实说
// 摆一个"将死了但不是上面任何名局"的局面，断言它给的是通用说法
// （宁可说"将死"，不要硬套一个听起来很厉害的名字）。
{
  const before = deserializeBoard(
    [
      '....k....', // 黑将 e9
      '.........',
      '.........',
      '.........',
      '.........',
      '.........',
      '.........',
      '.........',
      'R........', // 红车 a1
      '..N.K....', // 红马 c0、红帅 e0
    ].join('/'),
  )
  // 这一局：红车平到 e1？被红帅占着。改成红马 c0 跳到 e1 将军
  const move = legalMoves(before, 'red').find((m) => m.from === sq(9, 2) && m.to === sq(8, 4))
  if (!move) {
    bad('兜底：测试前提（这一步得是合法着法）', '红马 c0->e1 不在合法着法里')
  } else {
    const after = applyMove({ board: before, turn: 'red', history: [] }, move)
    const verdict = evaluateResult(after)
    if (verdict.over && verdict.reason === 'checkmate') {
      const pattern = classifyMate(after.board, move, 'black')
      assert(
        pattern !== null && typeof pattern.name === 'string' && pattern.name.length > 0,
        '认不出名局时也给得出一个说法（不会返回空）',
        pattern ? `${pattern.name} · ${pattern.detail}` : '返回了 null',
      )
    } else {
      // 这个局面不是将死 —— 那就换一条更稳的断言：识别器对"非将死局面"不该硬报杀法
      assert(
        classifyMate(after.board, move, 'black') === null || !verdict.over,
        '对未将死的局面不硬报杀法名',
        `引擎判定：${verdict.over ? verdict.reason : '未结束'}`,
      )
    }
  }
}

console.log(`\n\x1b[1m结果\x1b[0m  通过 \x1b[32m${passed}\x1b[0m  失败 \x1b[31m${failed}\x1b[0m\n`)
process.exit(failed === 0 ? 0 : 1)
