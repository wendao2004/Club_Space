/** 全部词（用于校验"选的词确实来自词库"之外的兜底，如自定义校验）。 */
export const ALL_DRAW_WORDS: string[] = DRAW_WORD_LEVELS.flatMap((l) => DRAW_WORDS[l])

/** 词 → 难度（同词多档时取最先出现的档）。 */
const LEVEL_OF = new Map<string, DrawWordLevel>()
for (const level of DRAW_WORD_LEVELS) {
  for (const word of DRAW_WORDS[level]) {
    if (!LEVEL_OF.has(word)) LEVEL_OF.set(word, level)
  }
}

export function drawWordLevel(word: string): DrawWordLevel {
  return LEVEL_OF.get(word) ?? 'medium'
}
